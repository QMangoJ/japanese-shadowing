import type { VocabularyInsight } from "./reviewedVocabulary";

// Hand-written, per-sentence explanations for the beginner course (Sections 3–56).
//
// Every sentence card has an entry keyed "<section>-<sentence>". Grammar is
// curated per sentence instead of being guessed with regular expressions, so a
// pattern such as 「とても」 can never be explained as 「〜ても」. Each grammar
// item is either:
//   - a key of `grammarPatterns` (optionally "key@literal" to name the exact
//     words in the sentence), or
//   - a [point, explanation, literal] tuple for sentence-specific points.
// `scripts/audit-sentence-insights.mjs` checks that every card has notes, that
// each pattern / literal actually occurs in that card's Japanese text, and that
// every card ends up with at least one word and one grammar point.

export type GrammarPattern = { point: string; explanation: string; test: RegExp };
export type GrammarRef = string | readonly [point: string, explanation: string, literal: string];
export type SentenceNote = {
	/** Grammar points, in reading order. */
	g: GrammarRef[];
	/** Extra words for this card (shown before glossary matches). */
	v?: VocabularyInsight[];
	/** Glossary terms that match this card's text but with a different meaning. */
	drop?: string[];
};

function w(term: string, reading: string | undefined, meaning: string, detail: string, aliases?: string[]): VocabularyInsight {
	return { term, reading, meaning, detail, aliases };
}

